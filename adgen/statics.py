"""Text layouts drawn in code with Pillow: the end card and static ads.

Brand text is never generated by an image model, so it is always spelled right.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

FONT = Path(__file__).parent.parent / "assets/fonts/InterVariable.ttf"
STATIC_SIZES = {"1x1": (1080, 1080), "4x5": (1080, 1350), "9x16": (1080, 1920)}
MARGIN = 80


def _font(size: int, weight: str = "Bold") -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(str(FONT), size)
    font.set_variation_by_name(weight)
    return font


def _wrap(draw: ImageDraw.ImageDraw, text: str, font, max_width: int) -> str:
    """Break text into lines that fit max_width."""
    lines = [""]
    for word in text.split():
        longer = f"{lines[-1]} {word}".strip()
        if draw.textlength(longer, font=font) <= max_width:
            lines[-1] = longer
        else:
            lines.append(word)
    return "\n".join(lines)


def end_card(brand: str, line: str, out: Path) -> None:
    """Full-screen end card: brand name with one line under it, centered."""
    img = Image.new("RGB", STATIC_SIZES["9x16"], "#141414")
    draw = ImageDraw.Draw(img)
    width, height = img.size
    draw.text((width / 2, height / 2 - 60), brand, fill="white", font=_font(120), anchor="mm")
    small = _font(56, "Regular")
    draw.multiline_text((width / 2, height / 2 + 80), _wrap(draw, line, small, width - 2 * MARGIN),
                        fill="#d0d0d0", font=small, anchor="ma", align="center")
    img.save(out)


def static_ad(image: Path, headline: str, brand: str, size: tuple[int, int], out: Path) -> None:
    """Static ad: the image cropped to size, headline and brand over a dark fade at the bottom."""
    width, height = size
    img = ImageOps.fit(Image.open(image).convert("RGB"), size, Image.Resampling.LANCZOS)
    fade = Image.linear_gradient("L").resize((width, height // 2))  # clear at top, dark at bottom
    img.paste("black", (0, height - height // 2), fade)
    draw = ImageDraw.Draw(img)
    big = _font(84)
    draw.multiline_text((MARGIN, height - 200), _wrap(draw, headline, big, width - 2 * MARGIN),
                        fill="white", font=big, anchor="ld", spacing=12)
    draw.text((MARGIN, height - MARGIN), brand.upper(), fill="white", font=_font(44), anchor="ls")
    img.save(out)


def app_screen(brief, out: Path) -> None:
    """A simple phone screenshot of the brief's app screen: brand bar, title, rows and one button.
    Drawn in code so that every name and amount is exact; image models garble screen text."""
    screen = brief.app_screen
    width, height = 1080, 2340
    img = Image.new("RGB", (width, height), "#f6f7f9")
    draw = ImageDraw.Draw(img)
    draw.rectangle((0, 0, width, 260), fill=screen.color)
    draw.text((MARGIN, 150), brief.brand, fill="white", font=_font(84), anchor="lm")
    draw.text((MARGIN, 380), screen.title, fill="#141414", font=_font(72), anchor="lm")
    top = 520
    for row in screen.rows:
        draw.rounded_rectangle((MARGIN, top, width - MARGIN, top + 200), radius=36, fill="white")
        draw.text((MARGIN + 50, top + 100), row.name, fill="#141414", font=_font(60, "Regular"), anchor="lm")
        draw.text((width - MARGIN - 50, top + 100), row.amount, fill="#141414", font=_font(60), anchor="rm")
        top += 240
    draw.rounded_rectangle((MARGIN, height - 420, width - MARGIN, height - 220), radius=100, fill=screen.color)
    draw.text((width / 2, height - 320), screen.button, fill="white", font=_font(68), anchor="mm")
    img.save(out)
